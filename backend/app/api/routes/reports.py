"""Meta Model API-powered reports (text generation, no GPU needed).

Privacy: only the opaque worker UUID is sent to the API — never the
worker's display name or any embedding.
"""

import json

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from app.api.deps import get_db
from app.core.config import settings
from app.integrations.meta_llama import MetaNotConfiguredError, summarize_shift
from app.models.safety import SafetyEvent, Shift, Worker

router = APIRouter(prefix="/reports", tags=["reports"])


@router.get("/shifts/{shift_id}/summary")
def shift_summary(shift_id: str, db: Session = Depends(get_db)):
    """End-of-shift safety brief generated by a Meta Llama text model."""
    if not settings.meta_configured:
        raise HTTPException(
            status_code=503,
            detail="Meta Model API is not configured. Set MODEL_API_KEY.",
        )
    shift = db.query(Shift).filter(Shift.id == shift_id).first()
    if not shift:
        raise HTTPException(status_code=404, detail="Shift not found")
    worker = db.query(Worker).filter(Worker.id == shift.worker_id).first()
    events = db.query(SafetyEvent).filter(SafetyEvent.shift_id == shift_id).all()

    # Anonymized: opaque worker code only — display names never leave the DB.
    worker_code = worker.id if worker else shift.worker_id
    brief_lines = [
        f"Worker code: {worker_code}",
        f"Date: {shift.date} | Status: {shift.status}",
        f"Violations: {shift.violation_count} | Compliant events: {shift.compliant_count}",
        f"MSD risk score: {shift.msd_risk_score}",
        "",
        "Events:",
    ]
    for e in events:
        meta = json.loads(e.metadata_json) if e.metadata_json else {}
        explanation = meta.get("explanation", "")
        brief_lines.append(
            f"- [{e.event_category}] {e.violation_type or 'compliant'} "
            f"({e.severity or '-'}, {e.camera_source}, t={e.video_timestamp}s)"
            + (f" — {explanation}" if explanation else "")
        )
    try:
        summary = summarize_shift("\n".join(brief_lines))
    except MetaNotConfiguredError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc
    except Exception as exc:  # noqa: BLE001 — surface API errors as 502
        raise HTTPException(
            status_code=502, detail=f"Meta Model API error: {exc}"
        ) from exc
    return {
        "shift_id": shift_id,
        "model": settings.meta_model_api_text_model,
        "summary": summary,
    }
